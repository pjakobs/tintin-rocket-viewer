import * as THREE from 'three';
import { OrbitControls } from 'three/addons/controls/OrbitControls.js';
import { LDrawLoader } from 'three/addons/loaders/LDrawLoader.js';
import { LDrawConditionalLineMaterial } from 'three/addons/materials/LDrawConditionalLineMaterial.js';
import { crossCheck } from './crosscheck.js';
import { initFeatures } from './features.js';
import { initHotspots } from './hotspots.js';
import { initStateSync } from './state.js';
import { axisOfSymmetry } from './geometry.js';

const MODEL_URL = '/model/tintin-rocket.ldr';
// Slim LDraw library holding only the ~535 parts/primitives this model uses
// (generated by scripts/prune-library.mjs). Point this at '/ldraw/' instead if
// you have the full library extracted there.
const LIBRARY_PATH = '/ldraw-min/';

// Shared material for LDraw part edge lines (see note in onModelLoaded).
const EDGE_MATERIAL = new THREE.LineBasicMaterial({ color: 0x1a1a1a, transparent: true, opacity: 0.35 });

// ---------------------------------------------------------------------------
// Scene / renderer
// ---------------------------------------------------------------------------
const app = document.getElementById('app');

const renderer = new THREE.WebGLRenderer({ antialias: true });
renderer.setPixelRatio(Math.min(window.devicePixelRatio, 2));
renderer.setSize(window.innerWidth, window.innerHeight);
renderer.toneMapping = THREE.ACESFilmicToneMapping;
renderer.toneMappingExposure = 1.1;
app.appendChild(renderer.domElement);

const scene = new THREE.Scene();
scene.background = new THREE.Color(0x0b0d12);

const camera = new THREE.PerspectiveCamera(45, window.innerWidth / window.innerHeight, 1, 100000);
camera.position.set(400, 320, 520);

const controls = new OrbitControls(camera, renderer.domElement);
controls.enableDamping = true;
controls.dampingFactor = 0.08;
controls.minDistance = 40;
controls.maxDistance = 4000;   // provisional; frameModel() refits it to the model

// The pivot frameModel() parks the model on: the rocket's axis at its mid-height.
// frameModel() moves the model onto this point, so it is simply the origin.
// Declared here rather than beside frameModel() so it is initialised before the
// top-level loader.parse() below, which can call frameModel() via its callback.
const HOME_TARGET = new THREE.Vector3(0, 0, 0);

// Lighting — a soft studio setup so bricks read clearly from any angle.
scene.add(new THREE.HemisphereLight(0xffffff, 0x333844, 1.6));
const key = new THREE.DirectionalLight(0xffffff, 2.2);
key.position.set(1, 1.4, 0.8);
scene.add(key);
const fill = new THREE.DirectionalLight(0xbcd4ff, 0.8);
fill.position.set(-1, 0.3, -0.7);
scene.add(fill);

// ---------------------------------------------------------------------------
// Model state (exposed for later hotspot / build-progress work)
// ---------------------------------------------------------------------------
export const model = {
  root: null,          // THREE.Group of the whole build
  parts: [],           // [{ object, partId, step }] — one per placed brick
  numSteps: 0,         // number of LDraw build steps (0 STEP metas)
};

// Missing-part tally: LDrawLoader warns on parts it can't fetch. Intercept to count.
const missingParts = new Set();
const origWarn = console.warn.bind(console);
console.warn = (...args) => {
  const msg = args.join(' ');
  const m = msg.match(/(?:Could not|Unable to).*?([\w-]+\.dat)/i) || msg.match(/([\w-]+\.dat).*?(?:not found|404)/i);
  if (m) missingParts.add(m[1].toLowerCase());
  origWarn(...args);
};

// ---------------------------------------------------------------------------
// Load
// ---------------------------------------------------------------------------
const statusEl = document.getElementById('status');
const progressEl = document.getElementById('progress');
const loadingEl = document.getElementById('loading');

function failLoad(err, msg) {
  console.error(err);
  loadingEl.classList.add('error');
  document.getElementById('load-msg').textContent = msg;
  document.getElementById('load-detail').textContent = String(err?.message ?? err);
  statusEl.textContent = 'Load failed';
}

const loader = new LDrawLoader();
loader.smoothNormals = true;
loader.setPartsLibraryPath(LIBRARY_PATH);
// Required since three r165+: the loader needs an explicit material for the
// conditional (edge-highlight) lines LDraw parts define.
loader.setConditionalLineMaterial(LDrawConditionalLineMaterial);

// Preload the official colour definitions so materials match real LEGO colours.
// NB: we must use loader.parse() below rather than loader.load(): load() calls
// setMaterials([]) internally, which would discard these preloaded colours and
// render every brick in the magenta "unknown colour" fallback. parse() keeps them.
try {
  await loader.preloadMaterials(`${LIBRARY_PATH}LDConfig.ldr`);
} catch (err) {
  failLoad(err, `Couldn't load LEGO colour definitions from ${LIBRARY_PATH}LDConfig.ldr — the parts library may be missing or incomplete.`);
  throw err;   // stop: parsing without colours renders everything magenta
}

statusEl.textContent = 'Loading model…';
progressEl.style.width = '30%';

try {
  const text = await fetch(MODEL_URL).then((r) => {
    if (!r.ok) throw new Error(`${MODEL_URL} → HTTP ${r.status}`);
    return r.text();
  });
  progressEl.style.width = '60%';
  loader.parse(
    text,
    (group) => onModelLoaded(group, text),
    (err) => failLoad(err, `The model file couldn't be parsed.`)
  );
} catch (err) {
  failLoad(err, `Couldn't load the model from ${MODEL_URL}.`);
}

function onModelLoaded(group, modelText) {
  // LDraw is -Y up; rotate 180° about X so the rocket stands upright.
  group.rotation.x = Math.PI;

  // NB: we deliberately do NOT call LDrawUtils.mergeObject() here. Merging would
  // collapse all bricks into a few material-batched buffers, destroying the
  // per-part hierarchy that the planned clickable hotspots and build-progress
  // animation depend on. ~1,250 separate meshes render comfortably at 60fps.

  // In this three.js build, LDrawLoader leaves the (non-conditional) edge
  // LineSegments with a null material, which crashes the renderer when it reads
  // material.visible. Give every material-less line a shared black edge material
  // so the crisp LDraw part outlines still render.
  group.traverse((child) => {
    if ((child.isLine || child.isLineSegments) && child.material == null) {
      child.material = EDGE_MATERIAL;
    }
  });

  // Tag every placed part so hotspots/build-progress can address them later.
  group.traverse((child) => {
    if (child.isMesh) {
      const partId = child.userData?.fileName || child.parent?.userData?.fileName || null;
      const step = child.userData?.constructionStep ?? child.parent?.userData?.constructionStep ?? 0;
      model.parts.push({ object: child, partId, step });
    }
  });

  model.root = group;
  model.numSteps = group.userData?.numBuildingSteps || 0;
  scene.add(group);

  frameModel(group);
  updateHUD();
  initFeatures(model);
  initHotspots({ THREE, scene, camera, renderer, controls, model, libraryPath: LIBRARY_PATH });
  initStateSync({ model, camera, controls });

  statusEl.textContent = 'Ready';
  loadingEl.classList.add('hidden');

  // Sanity check: reconcile the loaded model's brick count with the manual CSV.
  crossCheck(modelText).then((r) => {
    model.crossCheck = r;
    document.getElementById('stat-bricks').textContent = r.ldrBricks.toLocaleString();
    if (r.csvBricks != null) {
      document.getElementById('stat-csv').textContent = r.csvBricks.toLocaleString();
      const delta = r.csvBricks - r.ldrBricks;
      document.getElementById('stat-note').textContent =
        `${r.matchedParts} part IDs matched · Δ${delta > 0 ? '+' : ''}${delta} (minifig sub-parts & print variants the manual lists separately)`;
    } else {
      document.getElementById('stat-csv').textContent = 'n/a';
    }
  });
}

// Center the model at the origin and fit the camera to its bounding sphere.
function frameModel(object) {
  const box = new THREE.Box3().setFromObject(object);
  const center = box.getCenter(new THREE.Vector3());
  const axis = axisOfSymmetry(object);

  // Sit the model's axis on the world Y axis, and its mid-height at y=0, so the
  // orbit target below is a pivot that runs straight up through the rocket.
  object.position.sub(new THREE.Vector3(axis.x, center.y, axis.z));

  // Enclosing radius about the new origin. Measured from the re-centred box
  // rather than from size.length()/2, because shifting to the axis (not the bbox
  // centre) leaves the box slightly lopsided — the legs now reach further on one
  // side, and framing has to cover that longer reach.
  object.updateMatrixWorld(true);
  const shifted = new THREE.Box3().setFromObject(object);
  const radius = Math.max(shifted.max.length(), shifted.min.length());

  const dist = radius / Math.sin((camera.fov * Math.PI) / 180 / 2);
  camera.position.set(dist * 0.6, dist * 0.45, dist * 0.75);
  camera.near = radius / 100;
  camera.far = radius * 100;
  camera.updateProjectionMatrix();

  // Leave room to pull back far enough to frame the *exploded* model, not just the
  // assembled one — at the Explode slider's 300% each brick travels several times
  // its distance from the centre, so the assembled fit distance is nowhere near enough.
  controls.maxDistance = dist * 6;
  controls.target.copy(HOME_TARGET);
  controls.update();
}

// Undo panning.
//
// Right-drag pan slides the camera and the orbit target together, so afterwards
// OrbitControls pivots about wherever the target landed — off the rocket's axis
// by however far you panned, which reads as the model swinging around a point
// outside itself. state.js persists the target in the URL hash, so a stray pan
// also survives a reload and looks permanent.
//
// Moving both back by the same delta exactly reverses that: the rocket returns
// to the centre of the view and the pivot returns to its axis, while the current
// zoom and orbit angle are left untouched.
function recentre() {
  const delta = controls.target.clone().sub(HOME_TARGET);
  if (delta.lengthSq() === 0) return;
  camera.position.sub(delta);
  controls.target.copy(HOME_TARGET);
  controls.update(); // fires 'change', so state.js persists the corrected target
}

document.getElementById('recentre').addEventListener('click', recentre);
window.addEventListener('keydown', (e) => {
  if (e.target instanceof HTMLInputElement) return; // don't steal slider keys
  if (e.key.toLowerCase() === 'r' && !e.metaKey && !e.ctrlKey && !e.altKey) recentre();
});

function updateHUD() {
  document.getElementById('stat-parts').textContent = model.parts.length.toLocaleString();
  document.getElementById('stat-missing').textContent =
    missingParts.size ? `${missingParts.size} (${[...missingParts].join(', ')})` : '0';
}

// Expose viewer internals for the browser console and future feature scripts.
window.viewer = { THREE, scene, camera, renderer, controls, model };

// ---------------------------------------------------------------------------
// Render loop
// ---------------------------------------------------------------------------
function animate() {
  requestAnimationFrame(animate);
  controls.update();
  renderer.render(scene, camera);
}
animate();

window.addEventListener('resize', () => {
  camera.aspect = window.innerWidth / window.innerHeight;
  camera.updateProjectionMatrix();
  renderer.setSize(window.innerWidth, window.innerHeight);
});
